//! PostgreSQL 数据同步的 Plan 阶段：表/列元数据、主键、外键拓扑、DDL 与 SQL 生成。
//!
//! 这里保持纯函数（不连库），便于单测覆盖批次 SQL、外键环检测与指纹计算；
//! 真正的元数据查询在 `pg_data_sync` 引擎里完成。

use crate::config::DbType;
use crate::error::AppError;
use crate::sql_util::quote_ident_pg;
use serde::{Deserialize, Serialize};
use sha2::{Digest, Sha256};
use std::collections::{BTreeMap, BTreeSet};

#[derive(Debug, Clone, Serialize, Deserialize, PartialEq, Eq)]
pub struct PgColumnSpec {
    pub name: String,
    /// `format_type(atttypid, atttypmod)`，用于显式 cast，如 `numeric(12,2)`、`text[]`。
    pub formatted_type: String,
    pub type_name: String,
    pub type_schema: String,
    /// pg_type.typtype：b 基础 / e 枚举 / d 域 / r range / m 多值 range / c 复合 / p 伪类型
    pub type_kind: String,
    pub elem_type_name: Option<String>,
    pub elem_type_schema: Option<String>,
    pub elem_type_kind: Option<String>,
    pub not_null: bool,
    /// 'a' = GENERATED ALWAYS AS IDENTITY，'d' = GENERATED BY DEFAULT AS IDENTITY，'' = 非 identity
    pub identity: String,
    /// 's' = STORED 生成列，'' = 普通列
    pub generated: String,
    pub default_expr: Option<String>,
    pub generation_expr: Option<String>,
}

impl PgColumnSpec {
    pub fn is_writable(&self) -> bool {
        self.generated.is_empty()
    }

    pub fn is_generated(&self) -> bool {
        !self.generated.is_empty()
    }

    pub fn identity_always(&self) -> bool {
        self.identity == "a"
    }
}

#[derive(Debug, Clone, Serialize, Deserialize, PartialEq, Eq)]
pub struct PgEnumSpec {
    pub schema: String,
    pub name: String,
    pub labels: Vec<String>,
}

impl PgEnumSpec {
    pub fn key(&self) -> String {
        format!("{}.{}", self.schema, self.name)
    }
}

#[derive(Debug, Clone, Serialize, Deserialize, PartialEq, Eq)]
pub struct PgForeignKeySpec {
    pub name: String,
    /// `pg_get_constraintdef` 的结果，如 `FOREIGN KEY (user_id) REFERENCES users(id)`。
    pub definition: String,
    /// 被引用表的 schema 限定名，用于拓扑排序。
    pub referenced_table: String,
}

#[derive(Debug, Clone, Serialize, Deserialize, PartialEq, Eq)]
pub struct PgTablePlan {
    /// schema 限定名，如 `public.users`
    pub display_name: String,
    pub schema: String,
    pub name: String,
    pub columns: Vec<PgColumnSpec>,
    pub pk_columns: Vec<String>,
    pub target_exists: bool,
    pub target_columns: Vec<String>,
    pub target_pk_columns: Vec<String>,
    /// 目标表是否存在 GENERATED ALWAYS AS IDENTITY 列（写入时需要 OVERRIDING SYSTEM VALUE）。
    pub target_identity_always: bool,
    pub source_count: u64,
    pub foreign_keys: Vec<PgForeignKeySpec>,
    pub index_defs: Vec<String>,
    pub enum_types: Vec<PgEnumSpec>,
    /// 该表在 Plan 阶段产生的、需要在结果里如实告知的降级/改写说明。
    pub warnings: Vec<String>,
}

impl PgTablePlan {
    pub fn qualified(&self) -> String {
        qualified_table(&self.schema, &self.name)
    }

    pub fn writable_columns(&self) -> Vec<&PgColumnSpec> {
        self.columns.iter().filter(|c| c.is_writable()).collect()
    }

    pub fn pk_indexes_in_writable(&self) -> Result<Vec<usize>, AppError> {
        let writable = self.writable_columns();
        let mut out = Vec::with_capacity(self.pk_columns.len());
        for pk in &self.pk_columns {
            let idx = writable
                .iter()
                .position(|c| &c.name == pk)
                .ok_or_else(|| {
                    AppError::BadRequest(format!(
                        "表 {} 的主键列 {} 是生成列，当前无法按主键分批同步",
                        self.display_name, pk
                    ))
                })?;
            out.push(idx);
        }
        Ok(out)
    }

    pub fn pk_types(&self) -> Vec<String> {
        self.pk_columns
            .iter()
            .map(|pk| {
                self.columns
                    .iter()
                    .find(|c| &c.name == pk)
                    .map(|c| c.formatted_type.clone())
                    .unwrap_or_else(|| "text".to_string())
            })
            .collect()
    }

    pub fn has_identity(&self) -> bool {
        self.columns.iter().any(|c| !c.identity.is_empty())
    }
}

// ── 标识符 / 基础 SQL 片段 ──────────────────────────────

pub fn quote_ident(name: &str) -> String {
    quote_ident_pg(name)
}

pub fn qualified_table(schema: &str, table: &str) -> String {
    format!("{}.{}", quote_ident(schema), quote_ident(table))
}

/// 行值引用：单列 `"a"`，多列 `("a", "b")`。
pub fn row_ref(columns: &[String]) -> String {
    if columns.len() == 1 {
        quote_ident(&columns[0])
    } else {
        let cols = columns
            .iter()
            .map(|c| quote_ident(c))
            .collect::<Vec<_>>()
            .join(", ");
        format!("({cols})")
    }
}

/// 生成 `$start::t1, $start+1::t2 ...`，返回 (片段, 下一个参数序号)。
pub fn cast_params(types: &[String], start: usize) -> (String, usize) {
    let mut parts = Vec::with_capacity(types.len());
    let mut idx = start;
    for ty in types {
        parts.push(format!("${idx}::{ty}"));
        idx += 1;
    }
    (parts.join(", "), idx)
}

/// keyset 条件：`("a","b") > ($1::bigint,$2::text)`。
pub fn keyset_condition(pk_columns: &[String], pk_types: &[String], start: usize) -> (String, usize) {
    let (params, next) = cast_params(pk_types, start);
    (
        format!("{} > ({})", row_ref(pk_columns), params),
        next,
    )
}

// ── 批次 SQL 生成 ──────────────────────────────────────

/// 源表分批读取：所有可写列统一 `::text`，由目标端按列类型显式 cast 回去。
/// PostgreSQL 的文本 I/O 能无损覆盖数组、enum、jsonb、numeric、timestamptz、bytea 等类型。
pub fn batch_select_sql(plan: &PgTablePlan, has_cursor: bool, limit_placeholder: usize) -> String {
    let writable = plan.writable_columns();
    let cols = writable
        .iter()
        .map(|c| format!("{}::text AS {}", quote_ident(&c.name), quote_ident(&c.name)))
        .collect::<Vec<_>>()
        .join(", ");
    let mut sql = format!("SELECT {cols} FROM {}", plan.qualified());
    if has_cursor && !plan.pk_columns.is_empty() {
        let (cond, next) = keyset_condition(&plan.pk_columns, &plan.pk_types(), 1);
        sql.push_str(&format!(" WHERE {cond}"));
        // 调用方需要按 next 计算 LIMIT 占位符；这里用传入的序号覆盖。
        sql.push_str(&format!(" ORDER BY {}", order_by(&plan.pk_columns)));
        sql.push_str(&format!(" LIMIT ${limit_placeholder}"));
        let _ = next;
    } else {
        sql.push_str(&format!(" ORDER BY {}", order_by(&plan.pk_columns)));
        sql.push_str(&format!(" LIMIT ${limit_placeholder}"));
    }
    sql
}

pub fn order_by(pk_columns: &[String]) -> String {
    pk_columns
        .iter()
        .map(|c| quote_ident(c))
        .collect::<Vec<_>>()
        .join(", ")
}

/// 无主键表的整表读取（显式 allow_no_pk 时才使用）。
pub fn full_select_sql(plan: &PgTablePlan) -> String {
    let cols = plan
        .writable_columns()
        .iter()
        .map(|c| format!("{}::text AS {}", quote_ident(&c.name), quote_ident(&c.name)))
        .collect::<Vec<_>>()
        .join(", ");
    format!("SELECT {cols} FROM {}", plan.qualified())
}

/// 多行 upsert。`rows.len()` 决定 VALUES 的行数；参数从 `$1` 开始。
pub fn upsert_sql(plan: &PgTablePlan, row_count: usize) -> String {
    let writable = plan.writable_columns();
    let column_list = writable
        .iter()
        .map(|c| quote_ident(&c.name))
        .collect::<Vec<_>>()
        .join(", ");

    let mut values = Vec::with_capacity(row_count);
    let mut param = 1usize;
    for _ in 0..row_count {
        let mut cells = Vec::with_capacity(writable.len());
        for col in &writable {
            cells.push(format!("${param}::{}", col.formatted_type));
            param += 1;
        }
        values.push(format!("({})", cells.join(", ")));
    }

    let override_clause = if plan.target_identity_always {
        " OVERRIDING SYSTEM VALUE"
    } else {
        ""
    };

    if plan.pk_columns.is_empty() {
        // 无主键表：只能普通插入；幂等性由调用方在结果里如实声明。
        return format!(
            "INSERT INTO {} ({}){} VALUES {}",
            plan.qualified(),
            column_list,
            override_clause,
            values.join(", ")
        );
    }

    let conflict_target = plan
        .pk_columns
        .iter()
        .map(|c| quote_ident(c))
        .collect::<Vec<_>>()
        .join(", ");
    let non_pk = writable
        .iter()
        .filter(|c| !plan.pk_columns.contains(&c.name))
        .map(|c| format!("{} = EXCLUDED.{}", quote_ident(&c.name), quote_ident(&c.name)))
        .collect::<Vec<_>>();

    let conflict_action = if non_pk.is_empty() {
        "DO NOTHING".to_string()
    } else {
        format!("DO UPDATE SET {}", non_pk.join(", "))
    };

    format!(
        "INSERT INTO {} ({}){} VALUES {} ON CONFLICT ({}) {}",
        plan.qualified(),
        column_list,
        override_clause,
        values.join(", "),
        conflict_target,
        conflict_action
    )
}

/// mirror 模式：按主键删除目标库中源库不存在的一行。
pub fn delete_by_pk_sql(plan: &PgTablePlan) -> String {
    let (params, _) = cast_params(&plan.pk_types(), 1);
    format!(
        "DELETE FROM {} WHERE {} = ({})",
        plan.qualified(),
        row_ref(&plan.pk_columns),
        params
    )
}

/// mirror 模式：删除主键范围外的目标行（用于源表末尾之后的多余数据）。
pub fn delete_after_pk_sql(plan: &PgTablePlan) -> String {
    let (params, _) = cast_params(&plan.pk_types(), 1);
    format!(
        "DELETE FROM {} WHERE {} > ({})",
        plan.qualified(),
        row_ref(&plan.pk_columns),
        params
    )
}

pub fn delete_all_sql(plan: &PgTablePlan) -> String {
    format!("DELETE FROM {}", plan.qualified())
}

/// mirror 模式：读取目标表在 `(lower, upper]` 内的主键。
pub fn range_pk_select_sql(plan: &PgTablePlan, has_lower: bool, has_upper: bool) -> String {
    let pk_select = plan
        .pk_columns
        .iter()
        .map(|c| format!("{}::text", quote_ident(c)))
        .collect::<Vec<_>>()
        .join(", ");
    let mut param = 1usize;
    let mut conditions = Vec::new();
    if has_lower {
        let (cond, next) = keyset_condition(&plan.pk_columns, &plan.pk_types(), param);
        param = next;
        conditions.push(cond);
    }
    if has_upper {
        let (params, next) = cast_params(&plan.pk_types(), param);
        let _ = next;
        conditions.push(format!("{} <= ({})", row_ref(&plan.pk_columns), params));
    }
    let mut sql = format!("SELECT {pk_select} FROM {}", plan.qualified());
    if !conditions.is_empty() {
        sql.push_str(&format!(" WHERE {}", conditions.join(" AND ")));
    }
    sql.push_str(&format!(" ORDER BY {}", order_by(&plan.pk_columns)));
    sql
}

/// 序列对齐：空表用 `setval(seq, 1, false)`，非空表对齐到 MAX(col)。
pub fn sequence_setval_sql(plan: &PgTablePlan, column: &str) -> String {
    let col = quote_ident(column);
    format!(
        "SELECT setval((pg_get_serial_sequence($1, $2))::regclass, \
         COALESCE((SELECT MAX({col}) FROM {}), 1), \
         (SELECT MAX({col}) FROM {}) IS NOT NULL)",
        plan.qualified(),
        plan.qualified()
    )
}

// ── DDL 生成 ───────────────────────────────────────────

pub fn create_enum_sql(spec: &PgEnumSpec) -> String {
    let labels = spec
        .labels
        .iter()
        .map(|l| format!("'{}'", l.replace('\'', "''")))
        .collect::<Vec<_>>()
        .join(", ");
    format!(
        "CREATE TYPE {} AS ENUM ({})",
        qualified_table(&spec.schema, &spec.name),
        labels
    )
}

fn column_definition(col: &PgColumnSpec, warnings: &mut Vec<String>, table: &str) -> String {
    let mut sql = format!("{} {}", quote_ident(&col.name), col.formatted_type);
    if col.is_generated() {
        let expr = col
            .generation_expr
            .clone()
            .unwrap_or_else(|| "NULL".to_string());
        sql.push_str(&format!(" GENERATED ALWAYS AS ({expr}) STORED"));
        if col.not_null {
            sql.push_str(" NOT NULL");
        }
        return sql;
    }
    if !col.identity.is_empty() {
        sql.push_str(if col.identity == "a" {
            " GENERATED ALWAYS AS IDENTITY"
        } else {
            " GENERATED BY DEFAULT AS IDENTITY"
        });
    } else if let Some(default) = &col.default_expr {
        if default.trim_start().starts_with("nextval(") {
            // serial 的 nextval 默认值依赖源库的序列名。目标表是新建的，
            // 用 identity 等价承接，后续统一做序列对齐。
            sql.push_str(" GENERATED BY DEFAULT AS IDENTITY");
            warnings.push(format!(
                "表 {} 列 {} 的 serial 默认值在目标新建表上替换为 identity（序列名不沿用源库）",
                table, col.name
            ));
        } else {
            sql.push_str(&format!(" DEFAULT {}", default));
        }
    }
    if col.not_null {
        sql.push_str(" NOT NULL");
    }
    sql
}

pub fn create_table_sql(plan: &PgTablePlan) -> String {
    let mut warnings = Vec::new();
    let mut parts: Vec<String> = plan
        .columns
        .iter()
        .map(|c| column_definition(c, &mut warnings, &plan.display_name))
        .collect();
    if !plan.pk_columns.is_empty() {
        parts.push(format!(
            "PRIMARY KEY ({})",
            plan.pk_columns
                .iter()
                .map(|c| quote_ident(c))
                .collect::<Vec<_>>()
                .join(", ")
        ));
    }
    format!(
        "CREATE TABLE {} (\n  {}\n)",
        plan.qualified(),
        parts.join(",\n  ")
    )
}

pub fn add_foreign_key_sql(plan: &PgTablePlan, fk: &PgForeignKeySpec) -> String {
    format!(
        "ALTER TABLE {} ADD CONSTRAINT {} {}",
        plan.qualified(),
        quote_ident(&fk.name),
        fk.definition
    )
}

/// `pg_get_indexdef` 返回的 `CREATE INDEX` 加上幂等保护。
pub fn create_index_if_not_exists(def: &str) -> String {
    let trimmed = def.trim().trim_end_matches(';');
    if let Some(rest) = trimmed.strip_prefix("CREATE UNIQUE INDEX ") {
        return format!("CREATE UNIQUE INDEX IF NOT EXISTS {rest}");
    }
    if let Some(rest) = trimmed.strip_prefix("CREATE INDEX ") {
        return format!("CREATE INDEX IF NOT EXISTS {rest}");
    }
    trimmed.to_string()
}

// ── 外键拓扑排序 ───────────────────────────────────────

/// `edges` 为 `(子表, 被引用父表)`。父表必须先同步。
/// 存在环时返回环上（Kahn 剩余）的表名列表。
pub fn topological_order(
    tables: &[String],
    edges: &[(String, String)],
) -> Result<Vec<String>, Vec<String>> {
    let known: BTreeSet<&str> = tables.iter().map(|t| t.as_str()).collect();
    let mut indegree: BTreeMap<&str, usize> = tables.iter().map(|t| (t.as_str(), 0)).collect();
    let mut children: BTreeMap<&str, Vec<&str>> = BTreeMap::new();

    for (child, parent) in edges {
        if child == parent {
            continue;
        }
        let (Some(child), Some(parent)) = (
            known.get(child.as_str()).copied(),
            known.get(parent.as_str()).copied(),
        ) else {
            continue;
        };
        if !children
            .get(parent)
            .map(|v| v.contains(&child))
            .unwrap_or(false)
        {
            children.entry(parent).or_default().push(child);
            *indegree.get_mut(child).unwrap() += 1;
        }
    }

    let mut ready: BTreeSet<&str> = indegree
        .iter()
        .filter(|(_, d)| **d == 0)
        .map(|(t, _)| *t)
        .collect();
    let mut order = Vec::with_capacity(tables.len());
    while let Some(next) = ready.iter().next().copied() {
        ready.remove(next);
        order.push(next.to_string());
        if let Some(kids) = children.get(next) {
            for kid in kids {
                let d = indegree.get_mut(kid).unwrap();
                *d -= 1;
                if *d == 0 {
                    ready.insert(kid);
                }
            }
        }
    }

    if order.len() == tables.len() {
        Ok(order)
    } else {
        let cycle = indegree
            .into_iter()
            .filter(|(_, d)| *d > 0)
            .map(|(t, _)| t.to_string())
            .collect::<Vec<_>>();
        Err(cycle)
    }
}

// ── 作业指纹 ───────────────────────────────────────────

pub fn compute_job_key(
    source_label: &str,
    target_label: &str,
    mode: &str,
    batch_size: usize,
    plans: &[PgTablePlan],
) -> String {
    let mut hasher = Sha256::new();
    hasher.update(source_label.as_bytes());
    hasher.update(b"\x1f");
    hasher.update(target_label.as_bytes());
    hasher.update(b"\x1f");
    hasher.update(mode.as_bytes());
    hasher.update(b"\x1f");
    hasher.update(batch_size.to_string().as_bytes());
    hasher.update(b"\x1f");
    let mut sorted = plans.to_vec();
    sorted.sort_by(|a, b| a.display_name.cmp(&b.display_name));
    for plan in sorted {
        hasher.update(plan.display_name.as_bytes());
        hasher.update(b"\x1e");
        for col in &plan.columns {
            hasher.update(col.name.as_bytes());
            hasher.update(b"\x1d");
            hasher.update(col.formatted_type.as_bytes());
            hasher.update(b"\x1d");
            hasher.update(col.identity.as_bytes());
            hasher.update(b"\x1d");
            hasher.update(col.generated.as_bytes());
            hasher.update(b"\x1e");
        }
        for pk in &plan.pk_columns {
            hasher.update(b"\x1c");
            hasher.update(pk.as_bytes());
        }
        hasher.update(b"\x1f");
    }
    format!("{:x}", hasher.finalize())
}

/// 校验 Plan：没有主键的表默认拒绝；目标表缺列/主键不一致时拒绝。
pub fn validate_plan(plan: &PgTablePlan, allow_no_pk: bool) -> Result<(), AppError> {
    for col in &plan.columns {
        let kind = col.type_kind.as_str();
        if kind == "c" || kind == "p" {
            return Err(AppError::BadRequest(format!(
                "表 {} 列 {} 的类型 {} 是复合/伪类型，当前数据同步不支持；请先转换类型或排除该表",
                plan.display_name, col.name, col.formatted_type
            )));
        }
    }
    if plan.pk_columns.is_empty() && !allow_no_pk {
        return Err(AppError::BadRequest(format!(
            "表 {} 没有主键，无法分批与幂等续跑；如确认要整表复制，请显式设置 allow_no_pk=true",
            plan.display_name
        )));
    }
    if plan.pk_columns.is_empty() {
        return Ok(());
    }
    if !plan.target_exists {
        return Ok(());
    }
    for col in plan.writable_columns() {
        if !plan.target_columns.contains(&col.name) {
            return Err(AppError::BadRequest(format!(
                "目标表 {} 缺少列 {}，请先执行结构同步后再做数据同步",
                plan.display_name, col.name
            )));
        }
    }
    if plan.target_pk_columns != plan.pk_columns {
        return Err(AppError::BadRequest(format!(
            "表 {} 的主键不一致（源 {:?} / 目标 {:?}），无法使用 upsert",
            plan.display_name, plan.pk_columns, plan.target_pk_columns
        )));
    }
    Ok(())
}

pub fn db_type_must_be_pg(db_type: &DbType, role: &str) -> Result<(), AppError> {
    if matches!(db_type, DbType::PostgreSQL) {
        Ok(())
    } else {
        Err(AppError::BadRequest(format!(
            "PG 分阶段数据同步仅支持 PostgreSQL 连接；{role}当前为 {:?}",
            db_type
        )))
    }
}

