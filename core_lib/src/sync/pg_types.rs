//! PG 类型映射策略（纯函数部分）。
//!
//! 本实现采用「源端 `col::text` → 目标端 `$n::<formatted_type>`」的文本往返：
//! 对 PostgreSQL→PostgreSQL 同步，这能无损覆盖数组、enum、json/jsonb、
//! numeric(p,s)、timestamp/timestamptz、bytea、bool、uuid、range 等类型，
//! 同时避免在 Rust 侧为每种类型手写二进制编码。
//!
//! 需要特殊处理的是列级的写入语义：
//! - 生成列（`attgenerated = 's'`）不写入、不读取；
//! - identity 列照常复制值，但目标为 `GENERATED ALWAYS` 时需要
//!   `OVERRIDING SYSTEM VALUE`，否则 PostgreSQL 会拒绝显式值；
//! - 复合类型/伪类型在 Plan 阶段拒绝。

use super::pg_plan::PgColumnSpec;

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum ColumnWriteKind {
    /// 普通可写列。
    Copy,
    /// GENERATED ALWAYS AS IDENTITY：需要 OVERRIDING SYSTEM VALUE。
    IdentityAlways,
    /// GENERATED BY DEFAULT AS IDENTITY：可直接写入显式值。
    IdentityByDefault,
    /// 生成列：不写入。
    Generated,
}

pub fn classify_column(col: &PgColumnSpec) -> ColumnWriteKind {
    if col.is_generated() {
        return ColumnWriteKind::Generated;
    }
    match col.identity.as_str() {
        "a" => ColumnWriteKind::IdentityAlways,
        "d" => ColumnWriteKind::IdentityByDefault,
        _ => ColumnWriteKind::Copy,
    }
}

/// 复合类型（c）与伪类型（p）无法通过 `::text` 稳定往返，Plan 阶段拒绝。
pub fn is_supported_type(col: &PgColumnSpec) -> bool {
    !matches!(col.type_kind.as_str(), "c" | "p")
}

/// 收集该列涉及的自定义 enum 类型（含数组元素类型）。
pub fn enum_type_refs(col: &PgColumnSpec) -> Vec<(String, String)> {
    let mut out = Vec::new();
    if col.type_kind == "e" {
        out.push((col.type_schema.clone(), col.type_name.clone()));
    }
    if col.elem_type_kind.as_deref() == Some("e") {
        if let (Some(schema), Some(name)) = (&col.elem_type_schema, &col.elem_type_name) {
            out.push((schema.clone(), name.clone()));
        }
    }
    out
}

/// 目标端写值需要使用 OVERRIDING SYSTEM VALUE 时返回 true。
pub fn needs_overriding_system_value(columns: &[PgColumnSpec], target_identity_always: bool) -> bool {
    target_identity_always
        && columns
            .iter()
            .any(|c| c.is_writable() && classify_column(c) == ColumnWriteKind::IdentityAlways)
}

#[cfg(test)]
mod tests {
    use super::*;

    fn col(identity: &str, generated: &str, kind: &str) -> PgColumnSpec {
        PgColumnSpec {
            name: "c".to_string(),
            formatted_type: "text".to_string(),
            type_name: "text".to_string(),
            type_schema: "public".to_string(),
            type_kind: kind.to_string(),
            elem_type_name: None,
            elem_type_schema: None,
            elem_type_kind: None,
            not_null: false,
            identity: identity.to_string(),
            generated: generated.to_string(),
            default_expr: None,
            generation_expr: None,
        }
    }

    #[test]
    fn classifies_identity_and_generated() {
        assert_eq!(classify_column(&col("", "", "b")), ColumnWriteKind::Copy);
        assert_eq!(
            classify_column(&col("a", "", "b")),
            ColumnWriteKind::IdentityAlways
        );
        assert_eq!(
            classify_column(&col("d", "", "b")),
            ColumnWriteKind::IdentityByDefault
        );
        assert_eq!(
            classify_column(&col("", "s", "b")),
            ColumnWriteKind::Generated
        );
    }

    #[test]
    fn rejects_composite_and_pseudo_types() {
        assert!(!is_supported_type(&col("", "", "c")));
        assert!(!is_supported_type(&col("", "", "p")));
        assert!(is_supported_type(&col("", "", "b")));
        assert!(is_supported_type(&col("", "", "e")));
        assert!(is_supported_type(&col("", "", "d")));
    }

    #[test]
    fn collects_enum_refs_including_arrays() {
        let scalar = PgColumnSpec {
            type_kind: "e".to_string(),
            type_name: "mood".to_string(),
            type_schema: "public".to_string(),
            ..col("", "", "e")
        };
        assert_eq!(
            enum_type_refs(&scalar),
            vec![("public".to_string(), "mood".to_string())]
        );

        let array = PgColumnSpec {
            type_kind: "b".to_string(),
            elem_type_kind: Some("e".to_string()),
            elem_type_name: Some("mood".to_string()),
            elem_type_schema: Some("public".to_string()),
            ..col("", "", "b")
        };
        assert_eq!(
            enum_type_refs(&array),
            vec![("public".to_string(), "mood".to_string())]
        );
    }

    #[test]
    fn overriding_only_when_target_has_always_identity() {
        let cols = vec![col("a", "", "b")];
        assert!(needs_overriding_system_value(&cols, true));
        assert!(!needs_overriding_system_value(&cols, false));
        let by_default = vec![col("d", "", "b")];
        assert!(!needs_overriding_system_value(&by_default, true));
    }
}
